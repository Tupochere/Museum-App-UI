import 'package:brick_offline_first_with_supabase/brick_offline_first_with_supabase.dart';
import 'package:sqflite/sqflite.dart' show databaseFactory;
import 'package:supabase_flutter/supabase_flutter.dart';

class BrickConfig {
  static late OfflineFirstWithSupabaseRepository repository;

  static Future<void> initialize() async {
    final supabaseClient = Supabase.instance.client;

    repository = OfflineFirstWithSupabaseRepository(
      supabaseProvider: SupabaseProvider(
        supabaseClient,
        modelDictionary: supabaseModelDictionary,
      ),
      sqliteProvider: SqliteProvider(
        'mtengatenga_museum.sqlite',
        databaseFactory: databaseFactory,
        modelDictionary: sqliteModelDictionary,
      ),
      migrations: migrations,
      offlineRequestQueue: RestOfflineRequestQueue(
        client: supabaseClient.rest,
      ),
    );

    await repository.initialize();
  }

  // These will be auto-generated by build_runner
  static final supabaseModelDictionary = SupabaseModelDictionary({});
  static final sqliteModelDictionary = SqliteModelDictionary({});
  static final migrations = <Migration>[];
}
